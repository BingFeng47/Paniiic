// Art_List generator (final-art Req 1.1–1.4). Pure: builds the Markdown for docs/art-list.md
// from the renderer's own tables and the validator's view of assets/sprites/. The file is
// written by `npm run art:list` (tests/docs/artList.test.ts), never by hand.
import type { AnimationSpec } from './animationTable';
import type { AnimationName, EntityLook, SpriteEntity } from './entities';
import type { SpriteValidation } from './validate';

export interface ArtListTables {
  readonly animations: Readonly<Partial<Record<SpriteEntity, Partial<Record<AnimationName, AnimationSpec>>>>>;
  readonly looks: Readonly<Partial<Record<SpriteEntity, EntityLook>>>;
}

export type ArtStatus = 'placeholder' | 'partial' | 'done';

/** placeholder: no frames; partial: problems or fewer than suggested; done otherwise. */
export function artStatus(present: number, suggested: number, problems: number): ArtStatus {
  if (present === 0) return 'placeholder';
  if (problems > 0 || present < suggested) return 'partial';
  return 'done';
}

const round = (n: number): string => String(Math.round(n * 100) / 100);

export function renderArtList(tables: ArtListTables, validation: SpriteValidation): string {
  const lines = [
    '# Art list',
    '',
    'Generated by `npm run art:list` from `src/render/sprites/` and `assets/sprites/`. Do not edit',
    'by hand. Frames go in `assets/sprites/<entity>/<animation>/<NN>.svg`, numbered from `00`.',
    'Anchor is where the sprite stands (x, y in viewBox units).',
    '',
    '| Entity | Animation | viewBox | Anchor | fps | Frames (suggested / present) | Status |',
    '|---|---|---|---|---|---|---|',
  ];
  for (const entity of Object.keys(tables.animations) as SpriteEntity[]) {
    const look = tables.looks[entity];
    const row = tables.animations[entity] ?? {};
    const viewBox = look ? `0 0 ${look.box.w} ${look.box.h}` : '?';
    const anchor = look ? `bottom centre (${round(look.box.w / 2)}, ${look.box.h})` : '?';
    for (const animation of Object.keys(row) as AnimationName[]) {
      const spec = row[animation] as AnimationSpec;
      const key = `${entity}/${animation}`;
      const present = validation.present[key]?.length ?? 0;
      const prefix = `/assets/sprites/${key}/`;
      const problems = validation.problems.filter((p) => p.path.startsWith(prefix)).length;
      const status = artStatus(present, spec.suggestedFrames, problems);
      lines.push(
        `| ${entity} | ${animation} | \`${viewBox}\` | ${anchor} | ${round(spec.fps)} | ` +
          `${spec.suggestedFrames} / ${present} | ${status} |`,
      );
    }
  }
  lines.push('');
  return lines.join('\n');
}
